<?php

declare(strict_types=1);

namespace PhpGtk4\Tests;

use PHPUnit\Framework\TestCase;

/**
 * `gen/gir.php --install` runs on every `./ci.sh` (the `gen` stage regenerates in place
 * and fails on a diff), so it must not touch a file whose content it did not change.
 * It used to: rewriting identical sources bumped their mtimes, `make` then recompiled
 * src/gtk4.cpp and every generated class, and each run of the pipeline paid ~50 s for
 * nothing. Content decides what gets written; timestamps stay put.
 */
final class GeneratorIdempotenceTest extends TestCase
{
    private const string ROOT = __DIR__ . '/..';

    public function testRegeneratingAnUpToDateTreeTouchesNothing(): void
    {
        $generated = $this->generatedFiles();
        self::assertGreaterThan(50, count($generated), 'the generator owns far more files than that');

        clearstatcache();
        $before = array_map('filemtime', $generated);

        exec(sprintf(
            'cd %s && %s gen/gir.php --install 2>&1',
            escapeshellarg(self::ROOT),
            escapeshellarg(PHP_BINARY),
        ), $output, $status);
        if ($status !== 0) {
            self::markTestSkipped('gen/gir.php cannot run here: ' . implode("\n", $output));
        }

        clearstatcache();
        $after = array_map('filemtime', $generated);

        $touched = [];
        foreach ($generated as $i => $file) {
            if ($before[$i] !== $after[$i]) {
                $touched[] = substr($file, strlen(self::ROOT) + 1);
            }
        }
        self::assertSame(
            [],
            $touched,
            'the generator rewrote files it did not change, which makes `make` rebuild them',
        );
    }

    /** @return list<string> every file carrying the generator's header, plus its side outputs */
    private function generatedFiles(): array
    {
        $files = [];
        $roots = [self::ROOT . '/src', self::ROOT . '/tests/Generated'];
        foreach ($roots as $root) {
            $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root));
            foreach ($iterator as $file) {
                self::assertInstanceOf(\SplFileInfo::class, $file);
                if (!$file->isFile() || !in_array($file->getExtension(), ['cpp', 'php', 'inc', 'h'], true)) {
                    continue;
                }
                $path = $file->getPathname();
                if (str_contains((string) file_get_contents($path), 'GENERATED by gen/gir.php')) {
                    $files[] = $path;
                }
            }
        }
        sort($files);
        return $files;
    }
}
